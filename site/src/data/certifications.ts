/** Months after which an entry is marked as not reviewed recently. */
export const STALE_MONTHS = 12;

/** True when the entry's facts were read more than STALE_MONTHS before `today`. */
export function isStale(c: Pick<Certification, 'asOf'>, today: Date): boolean {
  const limit = new Date(Date.UTC(today.getUTCFullYear(), today.getUTCMonth() - STALE_MONTHS, today.getUTCDate()));
  return new Date(`${c.asOf}T00:00:00Z`) < limit;
}

/** The most recent `asOf`: the date the map shows. */
export function latestAsOf(list: readonly Certification[] = certifications): string {
  return list.reduce((max, c) => (c.asOf > max ? c.asOf : max), '');
}

/** The date in a retired entry's status note, if it has one. */
export function retiredDate(c: Certification): string {
  return c.statusNote?.match(/\d{4}-\d{2}-\d{2}/)?.[0] ?? '';
}

/** Host name of the issuer page, for the source link text. */
export function sourceHost(url: string): string {
  return new URL(url).hostname;
}

const LANE_IDS: CertLane[] = [...mapLanes.map((l) => l.id), 'engineering'];
const BAND_IDS = bands.map((b) => b.id);
const TYPES: CertType[] = ['certification', 'certificate'];
const STATUSES = Object.keys(statusWords) as CertStatus[];
const SCOPES: CertScope[] = ['core', 'context'];
const UNVERIFIED = Object.keys(unverifiedWords);
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;

/** Every problem with the list, as readable lines naming the entry. An empty list means it is sound. */
export function certificationProblems(today: Date): string[] {
  const problems: string[] = [];
  const ids = new Set<string>();
  const todayIso = today.toISOString().slice(0, 10);

  for (const c of certifications) {
    const w = c.id || '(no id)';
    const bad = (msg: string) => problems.push(`${w}: ${msg}`);

    if (!c.id) bad('id is empty');
    if (ids.has(c.id)) bad('duplicate id');
    ids.add(c.id);
    if (typeof c.url !== 'string' || !c.url.startsWith('https://')) bad('url must start with https://');
    if (typeof c.asOf !== 'string' || !ISO_DATE.test(c.asOf) || Number.isNaN(Date.parse(c.asOf))) {
      bad(`asOf must be an ISO date, got "${c.asOf}"`);
    } else if (c.asOf > todayIso) {
      bad(`asOf ${c.asOf} is in the future`);
    }
    if (!LANE_IDS.includes(c.lane)) bad(`bad lane "${c.lane}"`);
    if (!BAND_IDS.includes(c.band)) bad(`bad band "${c.band}"`);
    if (!TYPES.includes(c.type)) bad(`bad type "${c.type}"`);
    if (!STATUSES.includes(c.status)) bad(`bad status "${c.status}"`);
    if (!SCOPES.includes(c.scope)) bad(`bad scope "${c.scope}"`);
    const wantScope = c.lane === 'engineering' || c.status === 'retired' ? 'context' : 'core';
    if (c.scope !== wantScope) bad(`scope should be ${wantScope}`);
    if (!Array.isArray(c.requires)) bad('requires is not an array');
    else if (c.band === 'credential' && c.requires.length === 0) bad('band credential needs requires');
    if (typeof c.requirementText !== 'string' || c.requirementText.length === 0 || c.requirementText.length > 140) {
      bad('requirementText missing or over 140 characters');
    }
    if (!Array.isArray(c.unverified)) bad('unverified is not an array');
    else {
      for (const u of c.unverified) if (!UNVERIFIED.includes(u)) bad(`unknown unverified field "${u}"`);
      if (c.unverified.includes('status') && c.unverified.includes('name')) {
        bad('status and name are both unverified: nothing to publish');
      }
    }
    // The box text: a core box shows the acronym or the short name, a vendor box the short name.
    if (c.lane === 'engineering' ? !c.short : !c.acronym && !c.short) bad('no box text (acronym or short)');
    if (JSON.stringify(c).includes('\u2014')) bad('contains an em dash (U+2014)');
  }
  return problems;
}

