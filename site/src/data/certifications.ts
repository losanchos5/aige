// Personal AI governance credentials for /for/certifications: the map, the
// vendor block and the facts tables all read this one list.
//
// Editorial rules, enforced where a rule can be checked (certificationProblems):
//  - Every entry carries the URL of the issuer's own page its facts come from and
//    the date they were read. A fact not read on an issuer page stays empty and
//    is named in `unverified`; nothing is filled in from a third party.
//  - Status notes and level words are the issuer's, never the site's. The map
//    does not rank, score or recommend credentials.
//  - The entries are generated: edit handoffs/competencies-visual/certs.json (or
//    open an issue) and rerun gen-certifications-ts.mjs. The array below is
//    replaced as a whole; everything else in this file is hand-written.

export type CertLane =
  | 'governance'
  | 'audit'
  | 'risk'
  | 'management-system'
  | 'security'
  | 'foundations'
  | 'engineering';
export type CertBand = 'none' | 'training' | 'experience' | 'credential';
export type CertType = 'certification' | 'certificate';
export type CertStatus = 'live' | 'beta' | 'pilot' | 'presale' | 'announced' | 'retired';
export type CertScope = 'core' | 'context';
/** A field of an entry the issuer's page did not let us confirm. */
export type CertUnverified = 'band' | 'price' | 'acronym' | 'status' | 'governanceDomain' | 'name';

export interface Certification {
  id: string;
  issuer: string;
  /** The issuer's official name for the credential. */
  name: string;
  acronym: string | null;
  /** Text of the map box when `acronym` is null; the vendor block always uses it. */
  short?: string;
  type: CertType;
  typeNote: string | null;
  status: CertStatus;
  /** What the issuer says about the status (dates, conditions), in its words. */
  statusNote: string | null;
  lane: CertLane;
  band: CertBand;
  /** What the issuer requires before the exam, 140 characters at most. */
  requirementText: string;
  /** Prior credentials the issuer names (the "prior credential" band). */
  requires: string[];
  /** The level word the issuer gives its own credential, verbatim. */
  issuerLevel: string | null;
  price: string | null;
  governanceDomain: string | null;
  /** The issuer's page the facts were read on. */
  url: string;
  /** ISO date the facts were read. */
  asOf: string;
  unverified: CertUnverified[];
  scope: CertScope;
}

