// sync-catalogue.mjs: regenerate src/catalogue.generated.ts, the index of the
// templates-and-schemas library that get_template serves.
//
// The site publishes each JSON Schema, example and template as a static file
// (/schemas/<name>.v1.json, /schemas/examples/<name>.example.json,
// /templates/<name>.<ext>) but no machine-readable list of them, so the list is
// built here from the site sources and bundled with the server; the file
// contents are still fetched live from the site at call time. Run it after a
// schema or template is added:
//
//   npm run catalogue      (node --experimental-strip-types, Node 22.6 or later)
//
// Sources: site/public/schemas/*.v1.json (title, description, x-evidences,
// x-layer, x-pattern, x-lifecycle-stage), site/public/templates/* and the
// policy kit of site/src/data/templates.ts. test/catalogue.test.ts fails when
// the bundled catalogue and the site tree disagree.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const site = resolve(root, '..', '..', 'site');
const schemasDir = join(site, 'public', 'schemas');
const templatesDir = join(site, 'public', 'templates');

const { kit, stages, schemaOrder } = await import(pathToFileURL(join(site, 'src', 'data', 'templates.ts')).href);

const FORMAT = { md: 'markdown', yaml: 'yaml', yml: 'yaml', rego: 'rego', csv: 'csv', json: 'json' };
const stageLabel = new Map(stages.map((stage) => [stage.id, stage.label]));
const templateFiles = new Set(readdirSync(templatesDir));
const exampleFiles = new Set(readdirSync(join(schemasDir, 'examples')));

function patternId(url) {
  const hash = String(url).split('#')[1];
  return hash ?? String(url);
}

const schemaEntries = readdirSync(schemasDir)
  .filter((file) => file.endsWith('.v1.json'))
  .map((file) => {
    const name = file.replace(/\.v1\.json$/, '');
    const schema = JSON.parse(readFileSync(join(schemasDir, file), 'utf8'));
    const files = [{ role: 'schema', format: 'json', path: `/schemas/${file}` }];
    if (exampleFiles.has(`${name}.example.json`)) {
      files.push({ role: 'example', format: 'json', path: `/schemas/examples/${name}.example.json` });
    }
    for (const template of [...templateFiles].sort()) {
      const [stem, ext] = template.split(/\.(?=[^.]+$)/);
      if (stem === name) files.push({ role: 'template', format: FORMAT[ext] ?? ext, path: `/templates/${template}` });
    }
    const stage = schema['x-lifecycle-stage'] ?? null;
    return {
      name,
      kind: 'schema',
      title: schema.title,
      description: schema.description,
      stage,
      stageLabel: stage ? (stageLabel.get(stage) ?? null) : null,
      layers: schema['x-layer'] ?? [],
      patterns: (schema['x-pattern'] ?? []).map(patternId),
      evidences: schema['x-evidences'] ?? [],
      files,
    };
  })
  .sort((a, b) => {
    const ia = schemaOrder.indexOf(a.name);
    const ib = schemaOrder.indexOf(b.name);
    return (ia < 0 ? 999 : ia) - (ib < 0 ? 999 : ib) || a.name.localeCompare(b.name);
  });

const kitEntries = kit.map((item) => ({
  name: item.id,
  kind: 'kit',
  title: item.title,
  description: item.purpose,
  stage: 'organisation',
  stageLabel: stageLabel.get('organisation') ?? null,
  layers: [...item.layers],
  patterns: [...item.patterns],
  evidences: [...item.evidences],
  files: item.files.map((file) => {
    const ext = file.href.split('.').pop();
    return { role: 'template', format: FORMAT[ext] ?? ext, path: file.href };
  }),
}));

const entries = [...schemaEntries, ...kitEntries];
const names = new Set();
for (const entry of entries) {
  if (names.has(entry.name)) throw new Error(`catalogue: duplicate name ${entry.name}`);
  names.add(entry.name);
  for (const file of entry.files) {
    const local = file.path.startsWith('/templates/')
      ? join(templatesDir, file.path.slice('/templates/'.length))
      : join(site, 'public', file.path.slice(1));
    readFileSync(local); // throws when a listed file does not exist
  }
}

const banner = `// catalogue.generated.ts: GENERATED by scripts/sync-catalogue.mjs from the site
// sources (site/public/schemas, site/public/templates, site/src/data/templates.ts).
// Do not edit by hand: run \`npm run catalogue\` in tools/mcp-server.

import type { TemplateEntry } from './catalogue.js';

export const catalogue: readonly TemplateEntry[] = `;

writeFileSync(join(root, 'src', 'catalogue.generated.ts'), `${banner}${JSON.stringify(entries, null, 2)};\n`);
process.stdout.write(`catalogue: ${schemaEntries.length} schema(s), ${kitEntries.length} kit item(s)\n`);
